"""Qualitative inspection package and aligned complementary-image example viewer.

Assignment Section 10:
Deterministic example selection across key behavior categories:
1. Success: Correct image correct, swap changes appropriately.
2. Invariance: Model ignores image, outputs identical answer.
3. Sensitivity: Prediction changes under swap.
4. Failure: Both conditions incorrect.
5. No-image contrast: Control behavior without visual tokens.

Produces:
- qualitative_example_manifest.csv
- human_review_sheet.md (template with space for student observations, without AI report prose)
- aligned_complementary_examples.html (interactive visual inspection sheet)
"""
import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional
import pandas as pd

logger = logging.getLogger(__name__)


def select_qualitative_examples(
    df_grounding: pd.DataFrame,
    df_vqav2: pd.DataFrame,
    num_per_category: int = 2,
    seed: int = 6304,
) -> pd.DataFrame:
    """Deterministically categorizes and samples informative qualitative pairs."""
    selected_records = []

    for suite_name, df in [("grounding", df_grounding), ("vqav2", df_vqav2)]:
        # Group by pair_id
        pair_ids = df["pair_id"].unique()
        categorized: Dict[str, List[str]] = {
            "correct_swap_success": [],
            "image_ignored_identical": [],
            "swap_sensitive": [],
            "both_wrong": [],
        }

        for pid in pair_ids:
            p_df = df[df["pair_id"] == pid]
            corr_rows = p_df[p_df["condition"] == "correct"]
            swap_rows = p_df[p_df["condition"] == "complementary_swap"]

            if len(corr_rows) == 2 and len(swap_rows) == 2:
                # Predictions under correct
                c1, c2 = corr_rows["normalized_prediction"].iloc[0], corr_rows["normalized_prediction"].iloc[1]
                r1, r2 = corr_rows["reference"].iloc[0], corr_rows["reference"].iloc[1]
                # Predictions under swap
                s1, s2 = swap_rows["normalized_prediction"].iloc[0], swap_rows["normalized_prediction"].iloc[1]

                c1_match = (c1 == r1)
                c2_match = (c2 == r2)

                if c1 == c2 and s1 == s2 and c1 == s1:
                    categorized["image_ignored_identical"].append(pid)
                elif c1_match and c2_match and (s1 != c1 or s2 != c2):
                    categorized["correct_swap_success"].append(pid)
                elif not c1_match and not c2_match:
                    categorized["both_wrong"].append(pid)
                elif s1 != c1 or s2 != c2:
                    categorized["swap_sensitive"].append(pid)

        # Sample deterministically
        import numpy as np
        rng = np.random.RandomState(seed)

        for cat, pids in categorized.items():
            if pids:
                chosen = rng.choice(pids, size=min(len(pids), num_per_category), replace=False)
                for pid in chosen:
                    p_all = df[df["pair_id"] == pid]
                    for _, row in p_all.iterrows():
                        rec = row.to_dict()
                        rec["selection_category"] = cat
                        selected_records.append(rec)

    return pd.DataFrame(selected_records)


def export_human_review_sheet(
    df_selected: pd.DataFrame,
    output_path: str | Path,
) -> None:
    """Exports structured human inspection template in Markdown.

    Contains exact factual records and designated observation blocks for the student.
    Strictly avoids generative AI report narrative.
    """
    out_file = Path(output_path)
    out_file.parent.mkdir(parents=True, exist_ok=True)

    md = "# Qualitative Inspection & Human Review Sheet\n\n"
    md += "*Generated by Task 2 Qualitative Diagnostics. Fill in your observations in the designated sections below.*\n\n"
    md += "---\n\n"

    pair_ids = df_selected["pair_id"].unique()

    for pid in pair_ids:
        p_df = df_selected[df_selected["pair_id"] == pid]
        first = p_df.iloc[0]
        cat = first.get("selection_category", "general")
        suite = first.get("suite", "unknown")
        q = first.get("question", "")

        md += f"## Pair ID: `{pid}` ({suite.upper()} — Category: `{cat}`)\n\n"
        md += f"**Question:** *\"{q}\"*\n\n"

        # Table of predictions across conditions
        md += "| Image Role | Image ID | Reference Answer | Condition | Model Prediction | Norm Pred | NLL | Latency (s) |\n"
        md += "|---|---|---|---|---|---|---:|---:|\n"

        for _, row in p_df.iterrows():
            orig_id = row.get("original_image_id", "")
            supp_id = row.get("supplied_image_id", "None")
            role = "Image 1" if str(orig_id) == str(first.get("original_image_id")) else "Image 2"
            ref = row.get("reference", "")
            cond = row.get("condition", "")
            pred = row.get("prediction", "").replace("\n", " ")
            norm = row.get("normalized_prediction", "")
            nll = row.get("reference_nll", "N/A")
            sec = row.get("generation_time_sec", "N/A")

            md += f"| {role} | `{supp_id}` | `{ref}` | `{cond}` | {pred} | `{norm}` | {nll} | {sec} |\n"

        md += "\n**Student Analysis & Observations:**\n"
        md += "- *Visual grounding assessment:* \n"
        md += "- *Failure mode / bias explanation:* \n"
        md += "- *Language prior vs. visual reliance:* \n\n"
        md += "---\n\n"

    with open(out_file, "w", encoding="utf-8") as f:
        f.write(md)

    logger.info(f"Human review sheet exported to {out_file}")


